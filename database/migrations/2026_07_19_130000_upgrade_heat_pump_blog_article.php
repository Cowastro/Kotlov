<p><strong>Когда подходит:</strong> большой участок, дом для постоянного проживания, долгий горизонт окупаемости.</p>

<h3>Вода-вода</h3>
<p>Использует тепло грунтовых вод. Эффективный, но требовательный вариант: нужны подходящие условия, разрешения, качество воды и грамотное обслуживание.</p>

