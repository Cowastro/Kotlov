<p>Тепловой насос не “создаёт” тепло как электрический котёл. Он переносит тепло из воздуха, земли или воды в систему отопления дома. Поэтому на 1 кВт электричества он может дать условно 3-4 кВт тепла. Этот показатель называют COP.</p>

