<?php

namespace App\Services\Integrations;

use App\Models\IntegrationIssue;

class SupplierIntegrationIssueAdvisor
{
    /** @return array{owner:string,title:string,steps:array<int,string>,note:string} */
    public function advise(IntegrationIssue $issue): array
    {
        return match ($issue->type) {
            'integration_stale', 'integration_catalog_stale' => [
                'owner' => 'Поставщик',
                'title' => 'Запустить обмен из 1С / API',
                'steps' => [
                    'Проверьте регламентное задание, адрес подключения и пользователя интеграции.',
                    'Запустите один обмен каталога, цен и остатков вручную.',
                    'Убедитесь, что новый цикл появился в разделе «Журнал обмена».',
                ],
                'note' => 'KOTLOV принимает данные, но инициатором CommerceML-обмена является ваша 1С.',
            ],
            'integration_orders_stale', 'order_not_exported' => [
                'owner' => 'Поставщик',
                'title' => 'Восстановить получение заказов',
                'steps' => [
                    'Проверьте, что в узле обмена включена загрузка заказов с KOTLOV.',
                    'Запустите обмен заказами вручную и дождитесь ответа success.',
                    'Проверьте новый исходящий цикл в журнале обмена.',
                ],
                'note' => 'Не отмечайте заказ полученным вручную: KOTLOV фиксирует передачу только после подтверждения вашей системы.',
            ],
            'integration_statuses_stale', 'order_no_1c_response' => [
                'owner' => 'Поставщик',
                'title' => 'Вернуть актуальный статус заказа',
                'steps' => [
                    'Проверьте документ заказа и его текущий статус в 1С.',
                    'Включите выгрузку статусов в регулярный обмен и запустите цикл вручную.',
                    'Убедитесь, что поток «Статусы заказов» появился в журнале.',
                ],
                'note' => 'KOTLOV применяет только распознанные статусы и сохраняет историю изменений.',
            ],
            'order_status_conflict', 'order_status_unknown' => [
                'owner' => 'Совместно',
                'title' => 'Согласовать статус заказа',
                'steps' => [
                    'Проверьте точное значение и последовательность статуса документа в 1С.',
                    'Если значение ошибочно — исправьте его и повторите обмен.',
                    'Если это новый рабочий статус — передайте его администратору KOTLOV для добавления правила сопоставления.',
                ],
                'note' => 'До согласования KOTLOV не ухудшает состояние заказа и не применяет неизвестное значение автоматически.',
            ],
            'product_identity_collision' => [
                'owner' => 'Поставщик',
                'title' => 'Исправить повторяющийся идентификатор товара',
                'steps' => [
                    'Сравните указанные внешние ID, артикулы и штрихкоды в своей учётной системе.',
                    'Для разных товаров задайте разные стабильные артикулы или штрихкоды.',
                    'Повторите выгрузку; KOTLOV проверит связь без автоматического удаления карточек.',
                ],
                'note' => 'Не меняйте стабильный ID существующего товара без необходимости — это может потребовать ручного подтверждения связи.',
            ],
            'product_attention', 'product_unmatched', 'product_missing_category', 'product_missing_price' => $this->productAdvice($issue),
            default => [
                'owner' => 'KOTLOV',
                'title' => 'Передать проблему администратору KOTLOV',
                'steps' => [
                    'Проверьте объект и время последнего обмена.',
                    'Сообщите администратору KOTLOV название источника и текст проблемы.',
                ],
                'note' => 'Не удаляйте товар и не меняйте идентификаторы до проверки причины.',
            ],
        };
    }

    /** @return array{owner:string,title:string,steps:array<int,string>,note:string} */
    private function productAdvice(IntegrationIssue $issue): array
    {
        $missingPrice = (bool) data_get($issue->context, 'missing_price', $issue->type === 'product_missing_price');
        $unmatched = (bool) data_get($issue->context, 'unmatched', $issue->type === 'product_unmatched');
        $missingCategory = (bool) data_get($issue->context, 'missing_category', $issue->type === 'product_missing_category');

        if ($missingPrice && ($unmatched || $missingCategory)) {
            return [
                'owner' => 'Совместно',
                'title' => 'Передать цену и подготовить привязку',
                'steps' => [
                    'Поставщик: задайте положительную оптовую цену, стабильный артикул или штрихкод и повторите выгрузку.',
                    'KOTLOV: после обновления подтвердит существующую карточку и категорию сайта.',
                    'Проверьте результат в списке товаров после следующего обмена.',
                ],
                'note' => 'Поставщик исправляет исходные данные; решение о карточке и структуре каталога принимает KOTLOV.',
            ];
        }

        if ($missingPrice) {
            return [
                'owner' => 'Поставщик',
                'title' => 'Передать корректную оптовую цену',
                'steps' => [
                    'Проверьте вид цены и валюту в своей учётной системе.',
                    'Задайте положительную цену и повторите выгрузку предложений.',
                    'Убедитесь, что цена появилась в списке товаров KOTLOV.',
                ],
                'note' => 'Нулевая или отсутствующая цена не публикуется и не заменяется придуманным значением.',
            ];
        }

        return [
            'owner' => 'KOTLOV',
            'title' => $unmatched ? 'Подтвердить карточку товара' : 'Назначить категорию сайта',
            'steps' => [
                'Поставщик: проверьте название, артикул и штрихкод — они помогают найти существующую карточку.',
                'KOTLOV: подтвердит карточку и категорию либо запросит уточнение.',
                'Следите за состоянием товара после следующей проверки.',
            ],
            'note' => 'Привязку и структуру каталога меняет только администратор KOTLOV; поставщик видит результат без права случайного изменения.',
        ];
    }
}
