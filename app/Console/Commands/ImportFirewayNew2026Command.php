    private const CAT_PECHI = 61;   // Печи-камины

    public function handle(): int
    {
        $dryRun = $this->option('dry-run');

        if ($dryRun) {
            $this->info('=== DRY-RUN: изменений нет ===');
        }

        $products = $this->products();

        $toCreate = [];
        $skipped  = [];

        foreach ($products as $p) {
            $exists = Product::where('slug', $p['slug'])
                ->orWhere(function ($q) use ($p) {
                    $q->where('brand_id', self::BRAND_ID)->where('name', $p['name']);
                })->first();

            if ($exists) {
                $skipped[] = "[{$exists->id}] {$exists->name}";
            } else {
                $toCreate[] = $p;
            }
        }

        if ($skipped) {
            $this->warn('Уже существуют (пропускаем):');
            foreach ($skipped as $s) {
                $this->line("  ✅ $s");
            }
        }

        if (empty($toCreate)) {
            $this->info('Все товары уже созданы — нечего делать.');
            return 0;
        }

        $this->info('Будут созданы (' . count($toCreate) . ' шт.):');
        foreach ($toCreate as $p) {
            $this->line("  🆕 {$p['name']} — {$p['price']} BYN");
        }

        if ($dryRun) {
            $this->info('DRY-RUN: запустите без --dry-run для создания.');
            return 0;
        }

        foreach ($toCreate as $p) {
            $product = Product::create([
                'brand_id'            => self::BRAND_ID,
                'category_id'         => $p['category_id'],
                'name'                => $p['name'],
                'slug'                => $p['slug'],
                'price'               => $p['price'],
                'currency'            => 'BYN',
                'images'              => $p['images'],
                'content'             => $p['content'],
                'short_description'   => $p['short_description'],
                'specs'               => $p['specs'],
                'availability_status' => 'check',
                'is_active'           => true,
                'is_archived'         => false,
                'in_stock'            => false,
                'is_new'              => true,
            ]);
            $this->info("  ✅ Создан ID={$product->id}: {$product->name}");
        }

        $this->info('Готово! Создано: ' . count($toCreate) . ' товаров.');
        return 0;
    }

