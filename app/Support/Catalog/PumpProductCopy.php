<?php

namespace App\Support\Catalog;

use App\Models\Product;

/** Buyer copy uses only the exact model's already selected display facts. */
class PumpProductCopy
{
    public static function make(Product $product, string $slug, array $facts, string $sourceDescription = ''): array
    {
        $purpose = match ($slug) {
            'skvajinnye-nasosy' => 'Скважинный насос для подачи воды из скважины в систему водоснабжения дома или дачи.',
            'drenajnyie' => preg_match('/для (?:чистой|чистои) воды/ui', $product->name)
                ? 'Погружной насос для откачивания чистой воды из ёмкостей, бассейнов и затопленных помещений.'
                : (preg_match('/для (?:грязной|загрязненной|загрязнённой) воды/ui', $product->name)
                    ? 'Погружной насос для откачивания загрязнённой воды из резервуаров, котлованов и подвалов.'
                    : 'Дренажный насос для откачивания воды из ёмкостей и затопленных участков.'),
            'poverhnostnyie' => 'Поверхностный насос для подачи воды из источника к точкам водоразбора. Сам насос размещается вне воды.',
            'nasosnyie-stantsii' => 'Насосная станция для подачи воды в систему водоснабжения дома или дачи.',
            'tsirkulyatsionnyie' => 'Циркуляционный насос для перемещения воды в трубопроводе. Модель подбирают под назначение контура, подключения и условия работы.',
            'nasosy-dlya-kolodtsa' => str_contains(mb_strtolower($product->name), 'вибрацион')
                ? 'Вибрационный насос для подачи воды из колодца или ёмкости. При выборе учитывайте расположение водозабора и длину кабеля.'
                : 'Погружной насос для подачи воды из колодца или ёмкости в систему водоснабжения.',
            'fekalnye-nasosy' => 'Погружной фекальный насос для перекачивания сточных вод. Для выбора важны состав стоков, допустимые включения и высота отвода воды.',
            'kanalizatsionnye-nasosy' => 'Канализационная насосная установка для принудительного отвода бытовых стоков. Перед покупкой проверьте, какие санитарные приборы можно подключить к этой модели.',
            'nasosy-povysheniya-davleniya' => 'Насос для повышения давления воды в системе водоснабжения. Подходит для подбора решения там, где существующего напора недостаточно.',
            'mnogostupenchatye-nasosy' => 'Многоступенчатый насос для подачи воды. Модель выбирают по требуемому напору, расходу и условиям установки.',
            default => '',
        };
        $groups = [
            'Максимальный напор' => ['Макс. напор', 'Макс. высота напора', 'Максимальный напор', 'Макс. Напор (высота подъема)'],
            'Максимальная производительность' => ['Макс. расход', 'Макс. производительность', 'Максимальная производительность', 'Максимальный расход'],
            'Производительность' => ['Производительность'],
            'Расход' => ['Расход (пропускная способность)'],
            'Напор' => ['Напор (высота подъема)'],
            'Мощность' => ['Мощность'],
            'Мощность двигателя' => ['Мощность двигателя'],
            'Потребляемая мощность' => ['Потребляемая мощность'],
            'Максимальное погружение под воду' => ['Макс. погружение', 'Макс. глубина погружения', 'Максимальная глубина погружения'],
            'Диаметр насоса' => ['Ø насоса', 'Диаметр насоса'],
            'Длина насоса' => ['Длина насоса'],
            'Длина кабеля' => ['Длина кабеля', 'Длина электрического кабеля'],
            'Объём гидроаккумулятора' => ['Гидроаккумулятор', 'Объем накопительного бака', 'Объем бака'],
            'Монтажная длина' => ['Монтажная длина'],
        ];
        $facts = array_change_key_case(array_combine(array_map(fn ($key) => mb_strtolower(trim($key)), array_keys($facts)), array_values($facts)) ?: []);
        $highlights = [];
        $values = [];
        foreach ($groups as $label => $keys) {
            foreach ($keys as $key) {
                $value = $facts[mb_strtolower($key)] ?? null;
                if (! is_scalar($value) || ! preg_match('/\d/u', (string) $value)
                    || preg_match('/уточн|различаются|требует|\bI{1,3}\s*\d/iu', (string) $value) || mb_strlen((string) $value) > 100) {
                    continue;
                }
                $values[$label] = self::value((string) $value);
                $highlights[] = $label.' — '.$values[$label];
                break;
            }
        }
        $selection = match ($slug) {
            'skvajinnye-nasosy' => 'Перед покупкой сравните диаметр насоса с внутренним диаметром скважины. Затем учтите уровень воды, расстояние до дома и число одновременно открытых кранов.',
            'drenajnyie' => 'Выбирайте насос с учётом состава воды, размера частиц и высоты, на которую нужно её отвести.'
                .(preg_match('/3\s*[-–]?\s*в\s*[-–]?\s*1/ui', $product->name) ? ' Для этой модели допустимые загрязнения зависят от выбранной насадки.' : ''),
            'poverhnostnyie' => 'Для выбора важны расстояние до источника, высота забора воды и нужная подача. Сопоставьте эти условия с параметрами насоса перед покупкой.',
            'nasosnyie-stantsii' => 'Для выбора станции учитывайте источник воды, расстояние до дома и количество одновременно открытых кранов. Если в модели есть гидроаккумулятор, проверьте и его объём.',
            'tsirkulyatsionnyie' => 'Проверьте монтажную длину, размер соединений и питание. Режимы работы сравнивайте отдельно: значения для разных скоростей нельзя смешивать при подборе.',
            'nasosy-dlya-kolodtsa' => 'Перед покупкой проверьте размер колодца, уровень воды, допустимое погружение и расстояние до места подачи. Длины кабеля должно хватать для выбранного места установки.',
            'fekalnye-nasosy' => 'Сопоставьте допустимый размер включений с составом стоков. Наличие измельчителя нужно проверять для конкретной модели; оно не подразумевается самим названием «фекальный насос».',
            'kanalizatsionnye-nasosy' => 'Сравните размеры входных и выходного подключений, высоту подъёма и расстояние до канализации. Учитывайте температуру стоков от подключаемых приборов.',
            'nasosy-povysheniya-davleniya' => 'Для выбора важны давление на входе, требуемое давление после насоса и расход при открытых кранах. Проверьте питание и размеры соединений.',
            'mnogostupenchatye-nasosy' => 'Сравните требуемую подачу, высоту подъёма и условия подключения. Максимальные значения оценивают отдельно от обычного режима работы.',
            default => '',
        };
        if ($highlights !== []) {
            $selection .= ' Фактическая подача воды зависит от высоты подъёма и длины труб.';
        }

        $sentences = [];
        foreach (['Мощность двигателя', 'Потребляемая мощность', 'Мощность'] as $label) {
            if (isset($values[$label])) {
                $sentences[] = $label.' — '.$values[$label].'.';
            }
        }
        $hydraulics = [];
        foreach (['Максимальный напор', 'Максимальная производительность', 'Производительность', 'Напор', 'Расход'] as $label) {
            if (isset($values[$label])) {
                $hydraulics[] = ($hydraulics ? mb_strtolower($label) : $label).' — '.$values[$label];
            }
        }
        if ($hydraulics) {
            $sentences[] = implode(', ', $hydraulics).'.';
        }
        if (isset($values['Диаметр насоса'])) {
            $sentences[] = 'Диаметр насоса составляет '.$values['Диаметр насоса']
                .(isset($values['Длина насоса']) ? ', длина — '.$values['Длина насоса'] : '').'.';
        } elseif (isset($values['Длина насоса'])) {
            $sentences[] = 'Длина насоса — '.$values['Длина насоса'].'.';
        }
        if (isset($values['Максимальное погружение под воду'])) {
            $sentences[] = 'Допустимое погружение под воду — '.$values['Максимальное погружение под воду'].'.';
        }
        foreach (['Длина кабеля', 'Объём гидроаккумулятора', 'Монтажная длина'] as $label) {
            if (isset($values[$label])) {
                $sentences[] = $label.' — '.$values[$label].'.';
            }
        }

        $limitations = [];
        if (preg_match('/В случае применения для перекачки фекальных стоков,\s*насос не принимается в гарантийный ремонт/iu', $sourceDescription)) {
            $limitations[] = 'Перекачивание фекальных стоков не покрывается гарантией на эту модель.';
        }

        return ['summary' => $purpose, 'intro' => $purpose, 'limitations' => $limitations,
            'parameters' => implode(' ', $sentences),
            'selection' => $selection, 'highlights' => $highlights];
    }

    public static function value(string $value): string
    {
        return str_replace(['м3ч', 'м3/ч', ' uF', ' µF'], ['м³/ч', 'м³/ч', ' мкФ', ' мкФ'], $value);
    }
}
