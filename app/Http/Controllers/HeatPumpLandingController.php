    public function __invoke(string $landing)
    {
        $page = self::PAGES[$landing] ?? abort(404);
        $category = Category::query()->where('slug', 'teplovyie-nasosyi')->where('is_active', true)->firstOrFail();

        $products = Product::query()
            ->orderable()
            ->where('category_id', $category->id)
            ->when($page['product_filter'] === 'r290', fn ($query) => $query->where('name', 'like', '%R290%'))
            ->with(['category', 'brand'])
            ->orderByDesc('in_stock')
            ->orderBy('price')
            ->get();

        $canonical = 'https://kotlov.by/'.$landing;
        $schemaJson = json_encode([
            [
                '@context' => 'https://schema.org',
                '@type' => 'BreadcrumbList',
                'itemListElement' => [
                    ['@type' => 'ListItem', 'position' => 1, 'name' => 'Главная', 'item' => 'https://kotlov.by/'],
                    ['@type' => 'ListItem', 'position' => 2, 'name' => 'Тепловые насосы', 'item' => 'https://kotlov.by/teplovyie-nasosyi'],
                    ['@type' => 'ListItem', 'position' => 3, 'name' => $page['h1'], 'item' => $canonical],
                ],
            ],
            [
                '@context' => 'https://schema.org',
                '@type' => 'ItemList',
                'name' => $page['h1'],
                'numberOfItems' => $products->count(),
                'itemListElement' => $products->values()->map(fn (Product $product, int $index) => [
                    '@type' => 'ListItem',
                    'position' => $index + 1,
                    'name' => $product->name,
                    'url' => 'https://kotlov.by/'.$product->category->slug.'/'.$product->slug,
                ])->all(),
            ],
            [
                '@context' => 'https://schema.org',
                '@type' => 'FAQPage',
                'mainEntity' => collect($page['faq'])->map(fn (string $answer, string $question) => [
                    '@type' => 'Question',
                    'name' => $question,
                    'acceptedAnswer' => ['@type' => 'Answer', 'text' => $answer],
                ])->values()->all(),
            ],
        ], JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES);

        return view('pages.heat-pump-landing', compact('page', 'products', 'canonical', 'schemaJson'));
    }
}
