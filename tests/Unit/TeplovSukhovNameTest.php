<?php

namespace Tests\Unit;

use App\Support\TeplovSukhovName;
use PHPUnit\Framework\TestCase;

class TeplovSukhovNameTest extends TestCase
{
    public function test_names_of_different_price_lists_come_to_one_scheme(): void
    {
        $cases = [
            'Отвод моно Теплов и Сухов ОМ-Р 45*, 430, 0.8, Ø 150' => 'Отвод Моно Теплов и Сухов ОМ-Р 45°, 430-0,8, Ø 150',
            'ТиС Отвод 45° ОМ-Р 430-0.8 D115 (2S)' => 'Отвод Моно Теплов и Сухов ОМ-Р 45°, 430-0,8, Ø 115',
            'Отвод ТиС 45 OM-Р AISI 304 0,8-120' => 'Отвод Моно Теплов и Сухов ОМ-Р 45°, 304-0,8, Ø 120',
            'Отвод ТиС 45 OM-Р (430-0,8) MC Black (t &lt; 600°С)' => 'Отвод Моно Теплов и Сухов ОМ-Р 45°, 430-0,8, MC Black до 600 °С',
            'Тройник ТиС TРT-Р 87* 430, 0.8/430, 0.5, Ø 120/180' => 'Тройник Термо Теплов и Сухов ТРТ-Р 87°, 430-0,8/430-0,5, Ø 120/180',
            'ТиС Стандарт 50 Труба Термо L 500 ТТ-Р 304-0.8/304 D150/250 с хомутом' => 'Труба Термо Теплов и Сухов Стандарт 50 ТТ-Р, L500, 304-0,8/304, Ø 150/250, с хомутом',
            'Труба ТиС термо ТТ-Р 430, 0.8/430, 0.5, Ø 120/180 L1000' => 'Труба Термо Теплов и Сухов ТТ-Р, L1000, 430-0,8/430-0,5, Ø 120/180',
            'Конденсатоовод моно 430 0,5 мм Ø 120' => 'Конденсатоотвод Моно Теплов и Сухов, 430-0,5, Ø 120',
            'Фартук Теплов и сухов 180' => 'Фартук Теплов и Сухов, Ø 180',
            'ТиС Хомут трубный ХТ-Р на болте D 100 - ФР (М)' => 'Хомут трубный Теплов и Сухов ХТ-Р на болте, Ø 100',
            'Шибер-задвижка ТиС моно ф115' => 'Шибер-задвижка Моно Теплов и Сухов, Ø 115',
            'ТиС Труба L500 ТМ-Р 310-0.8 D150 «Энерго»' => 'Труба Моно Теплов и Сухов ТМ-Р, L500, 310-0,8, Ø 150, «Энерго»',
        ];
        foreach ($cases as $old => $new) {
            $this->assertSame($new, TeplovSukhovName::normalize($old), $old);
        }
    }

    public function test_a_name_in_the_scheme_stays_the_same(): void
    {
        foreach (['Отвод Моно Теплов и Сухов ОМ-Р 87°, 430-0,8, MC Black до 600 °С', 'Тройник Моно Теплов и Сухов ТРМ-Р 87°, 430-0,5, Ø 110',
            'Конденсатоотвод Термо Теплов и Сухов, 430-0,5, Ø 180, по наружному диаметру', 'Зонт Моно Теплов и Сухов ЗМ-Р, 430-0,5, чёрный, до 600 °С, Ø 150',
            'Труба телескопическая Термо Теплов и Сухов Стандарт 50 ТТТ-Р, L300-450, 304-0,8/304, Ø 115/210*, с хомутом',
            'Шибер-переход Моно/Термо Теплов и Сухов ШПМТ-Р, 430-0,8/430, MC Black до 600 °С, Ø 115/200'] as $name) {
            $this->assertSame($name, TeplovSukhovName::normalize($name), $name);
        }
    }

    public function test_items_outside_the_scheme_stay_as_they_are(): void
    {
        foreach (['Бак навесной ТиС Стандарт 80 горизонтальный (201-0,8)', 'Отвод 45* ТермоВент 304-0,8/430 115/150/210 (260)',
            'ТиС Проход перекрытия универсальный ППУ - Р 480х480 D220-260', 'Штанга регулируемая 150-300 мм',
            'Шибер - переход ТиС Моно-Термо ШПМТ-Р 115x200(430-0,8/430) MC Black (t краски &lt; 600°С) D115'] as $name) {
            $this->assertNull(TeplovSukhovName::normalize($name), $name);
        }
    }
}
