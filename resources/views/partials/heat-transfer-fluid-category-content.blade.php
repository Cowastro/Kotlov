                <h2 id="heat-fluid-guide-title">Как выбрать теплоноситель для отопления</h2>
                <p>
                    Теплоноситель (антифриз) заливают вместо воды, когда дом может остаться без отопления зимой:
                    дача, дом с периодическим проживанием, гараж, баня или котельная с риском отключения электричества.
                    Он не замерзает при морозе и не разрывает трубы и теплообменник котла, а ингибиторы коррозии
                    защищают металл, насос и уплотнения. Правильный выбор зависит от четырёх параметров.
                </p>
            </div>
            <ul class="gas-meter-guide__checklist">
                <li><strong>Основа</strong>Этиленгликоль — для закрытых систем, пропиленгликоль — для двухконтурных котлов и открытых систем.</li>
                <li><strong>Температура защиты</strong>−30 °C хватает для большинства домов, −65 °C — для неотапливаемых зимой.</li>
                <li><strong>Готовый или концентрат</strong>Концентрат дешевле на литр раствора, но его нужно точно разбавить.</li>
                <li><strong>Совместимость с котлом</strong>Проверьте паспорт котла: допускает ли он гликолевый теплоноситель.</li>
            </ul>
        </div>

        <div class="gas-meter-guide__types">
            <article class="gas-meter-guide__type">
                <h3>Готовый −30 °C на этиленгликоле</h3>
                <p>Самый массовый и доступный вариант для закрытых систем частного дома и дачи. Заливается без разбавления, хорошо прокачивается насосом.</p>
                <a href="/teplonositeli/teplonositel-zubr-30-etilenglikol-20-kg">Например, ZUBR -30</a>
