            <article class="gas-meter-guide__type">
                <h3>Пропиленгликоль (эко)</h3>
                <p>Нетоксичная основа: для двухконтурных котлов, бойлеров косвенного нагрева, открытых систем и мест, где теплоноситель может попасть в питьевую воду.</p>
                <a href="/teplonositeli/teplonositel-zubr-eko-30-propilenglikol-20-kg">Например, ZUBR Эко -30</a>
            </article>
            <article class="gas-meter-guide__type">
                <h3>−65 °C и концентраты</h3>
                <p>Запас по морозу для домов без отопления зимой. Концентрат и −65 °C можно разбавить водой до −20…−40 °C — так литр готового раствора обходится дешевле.</p>
                <a href="/teplonositeli/teplonositel-zubr-100-etilenglikol-20-kg">Суперконцентрат ZUBR 100</a>
            </article>
        </div>

        <div class="gas-meter-guide__lead" style="margin-top:24px">
            <div>
                <h2>Сколько теплоносителя покупать</h2>
                <p>
                    Объём системы складывается из котла, радиаторов, труб и примерно трети объёма расширительного бака.
                    Типичная система отопления дома 100–150 м² вмещает 80–150 литров. Учтите, что теплоноситель
                    тяжелее воды: в канистре 20 кг около 18–19 л, в канистре 10 кг — 9–9,5 л. Берите запас 10–15 % на доливку.
                </p>
            </div>
            <ul class="gas-meter-guide__checklist">
                <li><strong>Радиатор алюминиевый / биметалл</strong>0,2–0,45 л на секцию</li>
                <li><strong>Стальной панельный 500×1000, тип 22</strong>около 5–6 л</li>
                <li><strong>Труба 20 мм / 26 мм, 10 м</strong>около 2 л / 3,5 л</li>
                <li><strong>Настенный газовый котёл</strong>1–3 л; напольный твердотопливный — 20–80 л</li>
            </ul>
        </div>

